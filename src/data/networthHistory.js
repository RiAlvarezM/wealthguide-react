const MONTH_LABELS = ['Ene', 'Feb', 'Mar', 'Abr', 'May', 'Jun', 'Jul', 'Ago', 'Sep', 'Oct', 'Nov', 'Dic'];

export const formatHistoryLabel = (isoDate) => {
  const [year, month, day] = isoDate.split('-').map(Number);
  return `${day} ${MONTH_LABELS[month - 1]} ${year}`;
};

export const NETWORTH_HISTORY = RAW_HISTORY
  .map(([date, ahorro, inversion, jubilacion, deuda, prestamo]) => {
    const totalActivos = ahorro + inversion + jubilacion;
    const totalPasivos = deuda + prestamo;
    return {
      date,
      ahorro,
      inversion,
      jubilacion,
      deuda,
      prestamo,
      totalActivos,
      totalPasivos,
      netWorth: totalActivos - totalPasivos,
      debtRatio: totalActivos > 0 ? totalPasivos / totalActivos : 0,
    };
  })
  .sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0));

export function filterHistoryByRange(history, rangeLabel) {
  if (rangeLabel === 'Todo el Tiempo' || history.length === 0) return history;
  const years = rangeLabel === 'Últimos 5 Años' ? 5 : 10;
  const latest = new Date(history[history.length - 1].date);
  const cutoff = new Date(latest);
  cutoff.setFullYear(cutoff.getFullYear() - years);
  return history.filter((row) => new Date(row.date) >= cutoff);
}
